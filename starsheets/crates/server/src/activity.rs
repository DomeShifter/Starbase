//! A file's Activity (Details panel, like Google Drive): who did what, newest first. One small
//! list per file (`.starsheets/activity/<id>.jsonl`), written where the thing happens (main.rs,
//! after a request succeeds); who may read it is decided by the route (view access).
//! Saves that follow each other from the same person within ten minutes count as one "edited".

use std::fs;
use std::path::PathBuf;

use serde_json::{Value, json};

use crate::store::Store;

/// The most entries kept per file.
const KEEP: usize = 300;
/// Saves closer together than this, by the same person, are one "edited".
const MERGE_SECS: i64 = 600;

fn path(store: &Store, file: &str) -> PathBuf {
    // File ids are generated by us, but never let one climb out of the folder.
    let safe: String = file.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_').collect();
    store.meta().join("activity").join(format!("{safe}.jsonl"))
}

fn read(store: &Store, file: &str) -> Vec<Value> {
    fs::read_to_string(path(store, file)).unwrap_or_default().lines().filter_map(|l| serde_json::from_str(l).ok()).collect()
}

/// Notes that `who` did `kind` (created, edited, renamed, moved, shared, unshared, link,
/// commented, restored, trashed) to `file`, with a short `detail` ("Trip", "ann (can edit)").
pub fn note(store: &Store, file: &str, who: &str, kind: &str, detail: &str) {
    let now = crate::store::now() as i64;
    let p = path(store, file);
    let _ = fs::create_dir_all(p.parent().unwrap_or(&p));
    let mut all = read(store, file);
    if kind == "edited"
        && let Some(last) = all.last_mut()
        && last["kind"] == "edited"
        && last["by"] == who
        && now - last["at"].as_i64().unwrap_or(0) < MERGE_SECS
    {
        last["at"] = json!(now);
    } else {
        all.push(json!({ "at": now, "by": who, "kind": kind, "detail": detail }));
    }
    if all.len() > KEEP {
        all.drain(..all.len() - KEEP);
    }
    let text: String = all.iter().map(|e| format!("{e}\n")).collect();
    let _ = fs::write(&p, text);
}

/// The entries, newest first, each with the person's display name.
pub fn list(store: &Store, file: &str) -> Value {
    let users = crate::auth::users(store);
    let out: Vec<Value> = read(store, file)
        .into_iter()
        .rev()
        .map(|mut e| {
            let by = e["by"].as_str().unwrap_or("").to_string();
            let name = users.iter().find(|u| u.username == by).map_or(by.as_str(), |u| u.name.as_str()).to_string();
            e["name"] = json!(name);
            e
        })
        .collect();
    json!({ "activity": out })
}

/// What a Share dialog request did, as (kind, detail) entries.
pub fn from_sharing(body: &Value) -> Vec<(&'static str, String)> {
    let mut out = Vec::new();
    if let Some(people) = body.get("people").and_then(Value::as_object) {
        for (who, role) in people {
            out.push(match role.as_str().unwrap_or("") {
                "remove" => ("unshared", who.clone()),
                "edit" => ("shared", format!("{who} (can edit)")),
                "comment" => ("shared", format!("{who} (can comment)")),
                _ => ("shared", format!("{who} (can view)")),
            });
        }
    }
    if let Some(link) = body.get("link").and_then(Value::as_str) {
        out.push(("link", link.to_string()));
    }
    if let Some(on) = body.get("public").and_then(|p| p.get("on")).and_then(Value::as_bool) {
        out.push(("link", if on { "public link on" } else { "public link off" }.to_string()));
    }
    out
}
